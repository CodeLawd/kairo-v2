#!/usr/bin/env python3
"""Derive Bible pack verse numbering from pack source JSON files.

Some translations merge verses (GNT prints 1:6-7 as one verse numbered 6),
add verses (3 John 1:15), or leave whole books untranslated (TPT). Pack
validation walks each translation's exact numbering, so those differences
must be listed. This writes them as generated tables for both apps:

    python3 -I tools/pack-versification.py \
        --rust crates/kairo-domain/src/scripture/versification_data.rs \
        --ts ../kairo-presenter/src/lib/bible-versification-data.ts \
        EASY=/path/easy-bible.json GNT=/path/gnt-bible.json TPT=/path/tpt.json

Source shape is the pack converter's: books[].chapters[].verses[].verse.
A book whose chapters all hold no verses is recorded as absent.
"""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COUNTS = ROOT / "crates/kairo-store/src/db/verse_counts.rs"


def canon():
    src = COUNTS.read_text()
    body = src[src.index("&[") :]
    return [[int(n) for n in re.findall(r"\d+", m)] for m in re.findall(r"&\[([\d,\s_]*)\]", body)]


def derive(books, path):
    data = json.loads(Path(path).read_text())
    present = {}
    for book in data["books"]:
        for chapter in book["chapters"]:
            present[(book["index"], chapter["chapter"])] = {v["verse"] for v in chapter["verses"]}
    absent, rows = [], []
    for b, chapters in enumerate(books, start=1):
        if not any(present.get((b, c)) for c in range(1, len(chapters) + 1)):
            absent.append(b)
            continue
        for c, last in enumerate(chapters, start=1):
            have = present.get((b, c), set())
            if have == set(range(1, last + 1)):
                continue
            top = max(have, default=0)
            rows.append((b, c, top, sorted(set(range(1, top + 1)) - have)))
    extra = [k for k in present if k[0] > len(books) or k[1] > len(books[k[0] - 1])]
    if extra:
        raise SystemExit(f"{path}: chapters outside the canon: {extra[:5]}")
    return absent, rows


def rust(tables):
    out = [
        "//! Generated by `tools/pack-versification.py` from each pack's source JSON.",
        "//! Do not edit by hand; regenerate instead.",
        "",
        "use super::versification::VerseNumberingOverride;",
        "",
        "/// `(translation, book id, chapter, numbering)`.",
        "#[rustfmt::skip]",
        "pub(super) const GENERATED_OVERRIDES: &[(&str, u32, u32, VerseNumberingOverride)] = &[",
    ]
    for tid, (_, rows) in tables.items():
        for b, c, last, omitted in rows:
            out.append(
                f'    ("{tid}", {b}, {c}, VerseNumberingOverride {{ last_verse: {last}, omitted: &{omitted} }}),'
            )
    out += [
        "];",
        "",
        "/// Books a translation has not translated: every chapter holds no verses.",
        "#[rustfmt::skip]",
        "pub(super) const ABSENT_BOOKS: &[(&str, &[u32])] = &[",
    ]
    out += [f'    ("{tid}", &{absent}),' for tid, (absent, _) in tables.items() if absent]
    out += ["];", ""]
    return "\n".join(out)


def ts(tables):
    out = [
        "// Generated by kairo-gpui-kit `tools/pack-versification.py` from each pack's",
        "// source JSON. Do not edit by hand; regenerate instead.",
        "",
        "/** translation -> 'book:chapter' -> [lastVerse, ...omitted] */",
        "export const GENERATED_OVERRIDES: Record<string, Record<string, readonly number[]>> = {",
    ]
    for tid, (_, rows) in tables.items():
        cells = ", ".join(f"'{b}:{c}': {json.dumps([last, *omitted], separators=(',', ':'))}" for b, c, last, omitted in rows)
        out.append(f"  {tid}: {{ {cells} }},")
    out += [
        "}",
        "",
        "/** Books a translation has not translated: every chapter holds no verses. */",
        "export const ABSENT_BOOKS: Record<string, readonly number[]> = {",
    ]
    out += [f"  {tid}: {json.dumps(absent, separators=(',', ':'))}," for tid, (absent, _) in tables.items() if absent]
    out += ["}", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--rust", required=True)
    parser.add_argument("--ts", required=True)
    parser.add_argument("sources", nargs="+", help="ID=path/to/source.json")
    args = parser.parse_args()
    books = canon()
    assert len(books) == 66 and sum(map(sum, books)) == 31_102, "canon table changed"
    tables = {}
    for source in args.sources:
        tid, path = source.split("=", 1)
        tables[tid.upper()] = derive(books, path)
    Path(args.rust).write_text(rust(tables))
    Path(args.ts).write_text(ts(tables))
    for tid, (absent, rows) in tables.items():
        print(f"{tid}: {len(rows)} chapters renumbered, {len(absent)} books absent")


if __name__ == "__main__":
    main()
