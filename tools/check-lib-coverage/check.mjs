import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '../..')
const electron = resolve(process.env.KAIRO_ELECTRON_DIR ?? join(root, '../kairo-presenter'))
const args = process.argv.slice(2)
if (args.some(arg => arg !== '--regenerate')) {
  console.error('Usage: check-lib-coverage [--regenerate]')
  process.exit(2)
}
const require = createRequire(join(electron, 'package.json'))
const ts = require('typescript')

function files(dir, suffix) {
  return readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const path = join(dir, entry.name)
    return entry.isDirectory() ? files(path, suffix) : entry.name.endsWith(suffix) ? [path] : []
  }).sort()
}

const tsRoot = join(electron, 'src/lib')
const sourcePaths = files(tsRoot, '.ts')
const program = ts.createProgram(sourcePaths, {
  target: ts.ScriptTarget.ESNext,
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  skipLibCheck: true,
})
const checker = program.getTypeChecker()
const rustRoot = join(root, 'crates/kairo-domain/src')
const declarations = new Map()
for (const path of files(rustRoot, '.rs')) {
  const module = relative(rustRoot, path).replace(/(?:\/mod)?\.rs$/, '').replaceAll('/', '::')
  const source = readFileSync(path, 'utf8')
  for (const [, name] of source.matchAll(/^\s*pub\s+(?:(?:async|const)\s+)?(?:fn|enum|struct|type|const|static|trait|mod)\s+([A-Za-z_][A-Za-z_0-9]*)/gm)) {
    const full = `${module}::${name}`
    declarations.set(full, name)
  }
  for (const [, name] of source.matchAll(/#\[derive\([^)]*\bDefault\b[^)]*\)\]\s*(?:#\[[^\n]*\]\s*)*pub\s+struct\s+(\w+)/g)) {
    declarations.set(`${module}::${name}::default`, 'default')
  }
  for (const [, name] of source.matchAll(/^impl Default for ([A-Za-z_][A-Za-z_0-9]*)\s*\{/gm)) {
    declarations.set(`${module}::${name}::default`, 'default')
  }
}

const rules = JSON.parse(readFileSync(join(here, 'coverage.json'), 'utf8'))
const used = new Set()
const rows = []
const missing = []
function snake(name) {
  return name.replace(/([A-Z])([A-Z][a-z])/g, '$1_$2')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase()
}
for (const path of sourcePaths) {
  const source = program.getSourceFile(path)
  const module = checker.getSymbolAtLocation(source)
  if (!module) continue
  const file = relative(tsRoot, path)
  for (const symbol of checker.getExportsOfModule(module).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const key = `${file}#${symbol.name}`
    const exported = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol
    const declared = exported.declarations?.find(decl => decl.getSourceFile().fileName.startsWith(tsRoot + '/'))
    const origin = declared ? relative(tsRoot, declared.getSourceFile().fileName) : file
    const originKey = `${origin}#${exported.name}`
    const ruleKey = Object.hasOwn(rules.exports, key) ? key : originKey
    const rule = rules.exports[ruleKey]
    if (rule) used.add(ruleKey)
    const modules = rules.modules[origin] ?? [origin.replace(/\.ts$/, '').replaceAll('-', '_').replaceAll('/', '::')]
    const candidates = [...declarations].filter(([full, name]) =>
      modules.some(module => full.startsWith(module + '::')) &&
      [exported.name, snake(exported.name)].includes(name))
    const typeOnly = !(exported.flags & ts.SymbolFlags.Value)
    const typeCandidates = typeOnly ? [...declarations].filter(([, name]) => name === exported.name) : []
    const target = typeof rule === 'string' ? rule : candidates.length === 1 ? candidates[0][0] : typeCandidates.length === 1 ? typeCandidates[0][0] : null
    if (rule && typeof rule === 'object') {
      if (!rule.owner || !rule.reason) throw new Error(`Incomplete exclusion for ${ruleKey}`)
      rows.push([key, `Excluded (${rule.owner}): ${rule.reason}`])
    } else if (target && declarations.has(target)) {
      rows.push([key, `kairo_domain::${target}`])
    } else {
      rows.push([key, 'Uncovered'])
      missing.push(key)
    }
  }
}
const stale = Object.keys(rules.exports).filter(key => !used.has(key))
const report = '# Shared library export coverage\n\nGenerated by `check-lib-coverage --regenerate`.\n\n' +
  '| Electron export | Native counterpart or owner |\n|---|---|\n' +
  rows.map(([key, result]) => `| \`${key}\` | ${result.replaceAll('|', '\\|')} |\n`).join('')
const output = join(root, 'native-migration/lib-coverage.md')
if (args.includes('--regenerate')) writeFileSync(output, report)
else {
  let existing
  try { existing = readFileSync(output, 'utf8') } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }
  if (existing !== report) {
    console.error('Coverage report is stale. Run check-lib-coverage --regenerate.')
    process.exitCode = 1
  }
}
if (missing.length || stale.length) {
  console.error(`${missing.length} uncovered exports, ${stale.length} stale rules`)
  for (const key of stale) console.error(`Stale: ${key}`)
  for (const key of missing) console.error(`Uncovered: ${key}`)
  process.exitCode = 1
} else {
  console.log(`Checked ${rows.length} shared exports`)
}
